def _plain_details(section: str) -> str:
    """Оставить читаемый текст описания без Markdown ссылок и служебной разметки."""
    private_markers = ('student_code', 'ai_test_', '.env', 'llm_api_key', '/dev/tasks/')
    section = '\n'.join(
        line for line in section.splitlines()
        if not any(marker in line.lower() for marker in private_markers)
    )
    section = re.sub(r'\[([^]]+)\]\([^)]*\)', r'\1', section)
    section = re.sub(r'[`*]', '', section)
    section = re.sub(r'^#{1,6}\s*', '', section, flags=re.MULTILINE)
    return section.strip()


def _assignment_details() -> dict[int, str]:
    source = Path(settings.BASE_DIR) / 'tasks' / 'AI_ASSIGNMENTS.md'
    text = source.read_text(encoding='utf-8')
    sections = re.split(r'(?=^### \d+\. )', text, flags=re.MULTILINE)
    details = {}
    for section in sections:
        match = re.match(r'### (\d+)\. ', section)
        if match:
            details[int(match.group(1))] = _plain_details(section)
    return details


@require_GET
def author_assignments(request):
    details = _assignment_details()
    lessons = []
    for number in sorted({item.lesson for item in TASK_CATALOG if item.html_path}):
        tasks = []
        for item in TASK_CATALOG:
            if item.lesson != number or not item.html_path:
                continue
            student_action, ai_action = TASK_SUMMARIES[item.code]
            tasks.append({
                'definition': item,
                'student_action': student_action,
                'ai_action': ai_action,
                'details': details.get(item.number, ''),
            })
        lessons.append({'number': number, 'tasks': tasks})
    return render(request, 'courses/author_assignments.html', {
        'lessons': lessons,
        'task_count': sum(len(lesson['tasks']) for lesson in lessons),
    })
